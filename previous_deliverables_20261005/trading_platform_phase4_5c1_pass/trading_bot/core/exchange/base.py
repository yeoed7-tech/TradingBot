"""Adapter contract for Phase 3. Research never needs API credentials."""
from typing import Protocol
from trading_bot.core.events.models import Order

class ExchangeAdapter(Protocol):
    async def ticker(self,symbol: str) -> dict: ...
    async def ohlcv(self,symbol: str,since: int,limit: int) -> list: ...
    async def order_book(self,symbol: str) -> dict: ...
    async def balances(self) -> dict: ...
    async def positions(self) -> list: ...
    async def create_order(self,order: Order) -> dict: ...
    async def cancel_order(self,order_id: str) -> dict: ...
    async def order_status(self,order_id: str) -> dict: ...
    async def fills(self,order_id: str) -> list: ...
    async def fees(self,symbol: str) -> dict: ...
